/* The fixed-point constants and the table of da_sincos.c.

   Prints on stdout the C source to paste over the generated block of
   da_sincos.c, and a report on stderr. Qn denotes an integer standing
   for its quotient by 2^n. */
#include <assert.h>
#include <inttypes.h>
#include <stdio.h>
#include "gen_approx.h"

#define I0 1 // first and last table point, in steps
#define I1 10
#define SHIFT 52 // the step of the table is 2^SHIFT femtodegrees
#define STEP (UINT64_C(1) << SHIFT)
#define SPAN 100000 // the offsets tried, from the least
#define BIAS 0.44 // of the sines of the table, in units of Q64
#define LO 4003199668773775 // DECADE_LO, in femtodegrees here
#define N 4 // the coefficients of each polynomial

static mpfr_t K; // pi/180

/* The sine of n femtodegrees plus BIAS, as a Q64, in z; returns how
   far the two are, in units, or -1 when the sine is not in the lowest
   decade, below DECADE_LO 10^-16, and low is set. */
static double sine(mpz_t z, uint64_t n, int low)
{
  mpfr_t t;
  mpfr_init(t);
  mpfr_set_ui(t, n, MPFR_RNDN);
  mpfr_div_ui(t, t, 1000000000000000, MPFR_RNDN);
  mpfr_mul(t, t, K, MPFR_RNDN);
  mpfr_sin(t, t, MPFR_RNDN);
  double err = -1;
  if (!low || mpfr_cmp_d(t, LO * 1e-16) < 0) {
    bias(t, BIAS, 64);
    err = q(z, t, 64);
  }
  mpfr_clear(t);
  return err;
}

/* The largest distance of the sines of the lowest decade to their
   Q64, for an offset of the table. */
static double residual(mpz_t z, uint64_t offset)
{
  double worst = 0;
  for (int k = I0; k <= I1; k++) {
    double err = sine(z, k * STEP - offset, 1);
    if (err > worst) worst = err;
  }
  return worst;
}

/* (1 - sin θ/θ) / θ² and (1 - cos θ) / θ², for u = θ² */
static void g_over(mpfr_ptr y, mpfr_srcptr u)
{
  mpfr_t t;
  mpfr_init(t);
  mpfr_sqrt(t, u, MPFR_RNDN);
  mpfr_sin(y, t, MPFR_RNDN);
  mpfr_div(y, y, t, MPFR_RNDN);
  mpfr_ui_sub(y, 1, y, MPFR_RNDN);
  mpfr_div(y, y, u, MPFR_RNDN);
  mpfr_clear(t);
}

static void versine_over(mpfr_ptr y, mpfr_srcptr u)
{
  mpfr_t t;
  mpfr_init(t);
  mpfr_sqrt(t, u, MPFR_RNDN);
  mpfr_cos(y, t, MPFR_RNDN);
  mpfr_ui_sub(y, 1, y, MPFR_RNDN);
  mpfr_div(y, y, u, MPFR_RNDN);
  mpfr_clear(t);
}

/* u itself: the error that counts is that of u times the polynomial */
static void times_u(mpfr_ptr y, mpfr_srcptr u)
{
  mpfr_set(y, u, MPFR_RNDN);
}

static void define(const char *name, const mpfr_t v, int n,
                   const char *what)
{
  mpz_t i;
  mpz_init(i);
  double err = q(i, v, n);
  gmp_printf("#define %s UINT64_C(%Zd) // %s, Q%d\n", name, i, what, n);
  fprintf(stderr, "%s: %zu bits, rounded by %.3f unit\n",
          name, mpz_sizeinbase(i, 2), err);
  mpz_clear(i);
}

int main(void)
{
  mpfr_t v, f, t;
  mpz_t i, c;
  mpfr_t c4[N];
  approx_init();
  mpfr_inits(K, v, f, t, (mpfr_ptr)0);
  for (int k = 0; k < N; k++)
    mpfr_init(c4[k]);
  mpz_inits(i, c, (mpz_ptr)0);
  mpfr_const_pi(K, MPFR_RNDN);
  mpfr_div_ui(K, K, 180, MPFR_RNDN);

  puts("/* Generated by gen_sincos.c: do not edit. */");
  define("K69", K, 69, "pi/180");
  puts("");
  puts("// pi/180 10^-15-j, Q118: the radians of 10^-15-j degrees");
  puts("static const uint64_t T[10] = {");
  for (int j = 0; j < 10; j++) {
    mpfr_ui_pow_ui(v, 10, 15 + j, MPFR_RNDN);
    mpfr_div(v, K, v, MPFR_RNDN);
    q(i, v, 118);
    gmp_printf("  UINT64_C(%Zd),\n", i);
  }
  puts("};");
  puts("");
  // θ up to a step, above d in the table, and above DECADE_LO
  // femtodegrees, the end of the region of the polynomials alone
  assert(STEP >= LO);
  mpfr_set_ui(t, STEP, MPFR_RNDN);
  mpfr_set_si(v, -15, MPFR_RNDN);
  mpfr_exp10(v, v, MPFR_RNDN);
  mpfr_mul(t, t, v, MPFR_RNDN);
  mpfr_mul(t, t, K, MPFR_RNDN);
  mpfr_sqr(t, t, MPFR_RNDN);
  puts("// (1 - sin θ/θ) / θ² and (1 - cos θ) / θ² as polynomials in");
  printf("// θ² up to (%.4f degrees)², by Remez's exchange: the\n",
         STEP * 1e-15);
  puts("// magnitudes of their coefficients, of alternating signs,");
  puts("// highest degree first, in Q82, 76, 70, 64 and Q79, 73, 67, 61");
  static const struct { char name; fn *f; int n; } poly[] =
    { { 'G', g_over, 82 }, { 'V', versine_over, 79 } };
  for (int k = 0; k < 2; k++) {
    double err = remez(c4, poly[k].f, times_u, t, N);
    printf("static const uint64_t %c[%d] = {\n", poly[k].name, N);
    for (int j = 0; j < N; j++) {
      // the coefficient of degree N - 1 - j, of sign (-1)^(N-1-j)
      assert(mpfr_sgn(c4[j]) == ((N - 1 - j) % 2 ? -1 : 1));
      mpfr_abs(v, c4[j], MPFR_RNDN);
      q(i, v, poly[k].n - 6 * j);
      gmp_printf("  UINT64_C(%Zd),\n", i);
    }
    puts("};");
    puts("");
    fprintf(stderr, "%c: error %.2e, %.4f unit of Q64\n",
            poly[k].name, err, err * 0x1p64);
  }
  // In its lowest decade the sine is where the errors count most,
  // and the truncations of the kernel put it BIAS unit of Q64 below
  // what the table has, on average: the table has the sines that
  // much above, and the offset for which those of the lowest decade
  // are the closest to a Q64. With the least offset, DECADE_LO, the
  // least angle of the table, is the start of the slice I0.
  uint64_t offset = STEP - LO;
  double least = residual(i, offset);
  for (uint64_t o = offset + 1; o <= STEP - LO + SPAN; o++) {
    double r = residual(i, o);
    if (r < least) {
      least = r;
      offset = o;
    }
  }
  assert(LO + offset >> SHIFT == I0);
  assert(UINT64_C(45000000000000000) + offset >> SHIFT == I1);
  printf("// the table has t = i 2^SHIFT - OFFSET femtodegrees, for i "
         "from %d to %d\n", I0, I1);
  printf("#define SHIFT %d\n", SHIFT);
  printf("#define OFFSET UINT64_C(%" PRIu64 ")\n", offset);
  puts("");
  printf("// sin t + %.2f 2^-64 and cos t, Q64: the offset is the one\n",
         BIAS);
  puts("// whose sines below 0.4 are the closest to their Q64");
  printf("static const uint64_t table[%d][2] = {\n", I1 - I0 + 1);
  double largest = 0;
  for (int k = I0; k <= I1; k++) {
    sine(i, k * STEP - offset, 0);
    mpfr_set_ui(t, k * STEP - offset, MPFR_RNDN);
    mpfr_div_ui(t, t, 1000000000000000, MPFR_RNDN);
    mpfr_mul(t, t, K, MPFR_RNDN);
    mpfr_cos(v, t, MPFR_RNDN);
    double ec = q(c, v, 64);
    if (ec > largest) largest = ec;
    gmp_printf("  {UINT64_C(%Zd), UINT64_C(%Zd)},\n", i, c);
  }
  puts("};");
  fprintf(stderr, "offset: %" PRIu64 " femtodegrees, low sines "
          "within %.3f unit, cosines within %.3f\n", offset, least,
          largest);
  return 0;
}
