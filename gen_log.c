/* The fixed-point constants and the tables of da_log.c.

   Prints on stdout the C source to paste over the generated block of
   da_log.c, and a report on stderr. Qn denotes an integer standing for
   its quotient by 2^n. */
#include <assert.h>
#include <inttypes.h>
#include <stdio.h>
#include "gen_approx.h"

#define LO UINT64_C(4003199668773775)
#define HI UINT64_C(40031996687737742)
#define ZONES 14 // quarters of octaves from DECADE_LO to DECADE_HI
#define ZONE_E16 5 // the zone of 10^16
#define RAISE 2 // of the constant term of ATANH, in units of Q64

static mpfr_t LN10;
static mpfr_t C[16]; // the table being printed

/* The first len of C, as Qn integers. */
static void table(const char *name, int len, int n, int sign)
{
  mpz_t i;
  mpz_init(i);
  printf("static const %s %s[%d] = {\n",
         sign ? "int64_t" : "uint64_t", name, len);
  for (int k = 0; k < len; k++) {
    q(i, C[k], n);
    gmp_printf("  %s(%Zd),\n", sign ? "INT64_C" : "UINT64_C", i);
  }
  puts("};");
  puts("");
  mpz_clear(i);
}

/* The representation of the least da above v, in 40.03 to 400.3. */
static uint64_t rep(mpfr_srcptr v)
{
  mpfr_t t;
  mpfr_init(t);
  mpfr_mul_ui(t, v, 100000000000000, MPFR_RNDN);
  uint64_t i = mpfr_get_ui(t, MPFR_RNDZ);
  mpfr_clear(t);
  return LO + (i + 1 - LO | UINT64_C(128) << 55);
}

static void expm1_over(mpfr_ptr y, mpfr_srcptr d)
{
  mpfr_exp10(y, d, MPFR_RNDN);
  mpfr_sub_ui(y, y, 1, MPFR_RNDN);
  mpfr_div(y, y, d, MPFR_RNDN);
}

static void weight(mpfr_ptr y, mpfr_srcptr d)
{
  mpfr_exp10(y, d, MPFR_RNDN);
  mpfr_div(y, d, y, MPFR_RNDN);
}

/* 2 / ln 10 atanh(z) / z for w = z^2. */
static void atanh_over(mpfr_ptr y, mpfr_srcptr w)
{
  mpfr_t z;
  mpfr_init(z);
  mpfr_sqrt(z, w, MPFR_RNDN);
  mpfr_atanh(y, z, MPFR_RNDN);
  mpfr_div(y, y, z, MPFR_RNDN);
  mpfr_mul_2ui(y, y, 1, MPFR_RNDN);
  mpfr_div(y, y, LN10, MPFR_RNDN);
  mpfr_clear(z);
}

/* The inverse of atanh_over: the weight of its relative error. */
static void inverse(mpfr_ptr y, mpfr_srcptr w)
{
  atanh_over(y, w);
  mpfr_ui_div(y, 1, y, MPFR_RNDN);
}

/* The center of zone i: the middle of a quarter of an octave, but
   for the zone of 10^16. */
static uint64_t center(int i)
{
  int w = 52 + (i + 3) / 4, top = 4 + (i + 3) % 4;
  return i == ZONE_E16 ? UINT64_C(10000000000000000)
    : (uint64_t)(2 * top + 1) << w - 4;
}

int main(void)
{
  mpfr_t v, z, top;
  mpz_t i;
  approx_init();
  mpfr_inits(LN10, v, z, top, (mpfr_ptr)0);
  mpz_init(i);
  for (int k = 0; k < 16; k++)
    mpfr_init(C[k]);
  mpfr_log_ui(LN10, 10, MPFR_RNDN);

  puts("/* Generated by gen_log.c: do not edit. */");
  // The product m F17 >> 56 loses half a unit of Q64 on average,
  // and an excess of F17 of e units adds e m 2^-56: the two cancel
  // for the m of an f of log10 4.0032, where 10^f is at the top of
  // its lowest decade and the errors count most.
  mpfr_set_d(v, LO * 1e-15, MPFR_RNDN);
  mpfr_log10(v, v, MPFR_RNDN);
  double excess = 0x1p55 / (1e17 * mpfr_get_d(v, MPFR_RNDN));
  mpfr_set_si(v, -17, MPFR_RNDN);
  mpfr_exp10(v, v, MPFR_RNDN);
  mpfr_mul_2ui(z, v, 120, MPFR_RNDN);
  bias(v, excess, 120);
  q(i, v, 120);
  mpfr_z_sub(z, i, z, MPFR_RNDN);
  double err = mpfr_get_d(z, MPFR_RNDN);
  fprintf(stderr, "F17: %.3f unit above 10^-17, for %.3f\n", err,
          excess);
  gmp_printf("#define F17 UINT64_C(%Zd) // 10^-17 + %.2f unit, Q120\n",
             i, err);
  puts("// the least x such that 10^x rounds to infinity, and the");
  puts("// least such that 10^-x rounds to zero");
  mpfr_set_ui(v, HI + 4, MPFR_RNDN);
  mpfr_log10(v, v, MPFR_RNDN);
  mpfr_add_ui(v, v, 112, MPFR_RNDN);
  printf("#define OVER UINT64_C(%" PRIu64 ")\n", rep(v));
  mpfr_set_ui(v, 2, MPFR_RNDN);
  mpfr_log10(v, v, MPFR_RNDN);
  mpfr_add_ui(v, v, 142, MPFR_RNDN);
  printf("#define UNDER UINT64_C(%" PRIu64 ")\n", rep(v));
  puts("");

  puts("// 10^(i/16 - 1), Q64");
  for (int k = 0; k < 16; k++) {
    mpfr_set_si(C[k], k - 16, MPFR_RNDN);
    mpfr_div_2ui(C[k], C[k], 4, MPFR_RNDN);
    mpfr_exp10(C[k], C[k], MPFR_RNDN);
  }
  table("P", 16, 64, 0);

  // the error of 10^d - 1 relative to 10^d is that of 10^(f-1)
  mpfr_set_ui_2exp(top, 1, -4, MPFR_RNDN);
  err = remez(C, expm1_over, weight, top, 8);
  for (int k = 0; k < 8; k++)
    assert(mpfr_sgn(C[k]) > 0);
  puts("// (10^d - 1) / d for d up to 1/16, Q62");
  table("EXPM1", 8, 62, 0);
  fprintf(stderr, "10^d: relative error %.2e\n", err);

  // the largest z = |sd - c| / (sd + c), reached in the zone of 10^16
  mpfr_set_zero(z, 1);
  for (int k = 0; k < ZONES; k++)
    for (int e = 4; e <= 5; e++) {
      uint64_t s = (uint64_t)((3 + k) % 4 + e) << 49 + (3 + k) / 4;
      uint64_t c = center(k);
      mpfr_set_si(v, (int64_t)s - (int64_t)c, MPFR_RNDN);
      mpfr_div_ui(v, v, s + c, MPFR_RNDN);
      if (mpfr_cmpabs(v, z) > 0)
        mpfr_abs(z, v, MPFR_RNDN);
    }
  assert(mpfr_cmp_ui_2exp(z, 1, -4) < 0);
  mpfr_sqr(top, z, MPFR_RNDN);
  err = remez(C, atanh_over, inverse, top, 6);
  for (int k = 0; k < 6; k++)
    assert(mpfr_sgn(C[k]) > 0);
  // Next to 1, the truncations of the inverse and of the products
  // all make the logarithm smaller: the constant term is that much
  // above its fit, which halves the largest error there.
  bias(C[5], RAISE, 64);
  printf("// 2 / ln 10 atanh(z) / z in z^2, z up to %.4f, Q64, the\n",
         mpfr_get_d(z, MPFR_RNDN));
  printf("// constant term %d units above\n", RAISE);
  table("ATANH", 6, 64, 0);
  fprintf(stderr, "atanh(z) / z: relative error %.2e\n", err);

  printf("#define ZONE_E16 %d // the zone of 10^16\n", ZONE_E16);
  puts("// log10 of the centers of the zones, Q63");
  for (int k = 0; k < ZONES; k++) {
    mpfr_set_ui(C[k], center(k), MPFR_RNDN);
    mpfr_div_ui(C[k], C[k], 10000000000000000, MPFR_RNDN);
    mpfr_log10(C[k], C[k], MPFR_RNDN);
  }
  table("T", ZONES, 63, 1);
  return 0;
}
